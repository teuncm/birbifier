import { test, expect } from '@playwright/test'

for (const width of [320, 1280]) {
  test(`status dot and label stay fixed across playback states at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 812 })
    await page.goto('/')
    await page.getByRole('button', { name: 'Reset', exact: true }).click()
    await page.locator('#duration').fill('0.5')
    await page.locator('#pause').fill('1')
    const status = page.getByRole('status', { name: 'Playback status' })
    const geometry = () => status.evaluate(status => [...status.children].map(element => {
      const rect = element.getBoundingClientRect()
      return [rect.x, rect.y, rect.width, rect.height]
    }))
    await expect(status).toHaveText('Ready')
    const ready = await geometry()
    await page.getByRole('button', { name: 'Play song', exact: true }).click()
    await expect(status).toHaveText('Playing')
    expect(await geometry()).toEqual(ready)
    await expect(status).toHaveText('Pause')
    expect(await geometry()).toEqual(ready)
    await page.getByRole('button', { name: 'Stop song', exact: true }).click()
    await expect(status).toHaveText('Ready')
    expect(await geometry()).toEqual(ready)
  })
}

for (const width of [320, 375, 768]) {
  test(`playback stays reachable while editing at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 812 })
    await page.goto('/')
    await page.getByRole('button', { name: 'Reset', exact: true }).click()
    const controls = page.getByRole('group', { name: 'Playback controls', exact: true })
    const player = page.getByRole('region', { name: 'Playback', exact: true })
    await expect(player).toHaveCSS('position', 'fixed')
    const bounds = await player.boundingBox()
    expect(bounds.x).toBe(0)
    expect(bounds.width).toBe(width)
    expect(bounds.y + bounds.height).toBe(812)
    await expect(player).toHaveCSS('border-radius', '0px')
    await expect(page.getByRole('heading', { name: 'Playback', exact: true })).not.toBeVisible()
    await expect(player.getByRole('img', { name: 'Waveform preview of the current song' })).toBeVisible()
    await expect(page.locator('.waveform-display')).toHaveCSS('height', '32px')
    await page.locator('#pause').scrollIntoViewIfNeeded()
    for (const name of ['Play song', 'Repeat song', 'Download (WAV)']) {
      const button = controls.getByRole('button', { name, exact: true })
      expect(await button.evaluate(button => {
        const rect = button.getBoundingClientRect()
        return rect.top >= 0 && rect.bottom <= innerHeight && button.contains(document.elementFromPoint(rect.left + rect.width / 2, rect.top + rect.height / 2))
      })).toBe(true)
    }
    const scroll = await page.evaluate(() => scrollY)
    await controls.getByRole('button', { name: 'Play song', exact: true }).click()
    await expect(controls.getByRole('button', { name: 'Stop song', exact: true })).toBeVisible()
    const cursor = player.locator('[data-playback-cursor]')
    await expect.poll(async () => Number(await cursor.getAttribute('x1'))).toBeGreaterThan(0)
    expect(await page.evaluate(() => scrollY)).toBe(scroll)
    const pending = page.waitForEvent('download')
    await controls.getByRole('button', { name: 'Download (WAV)', exact: true }).click()
    expect((await pending).suggestedFilename()).toBe('birbifier-song.wav')
    expect(await page.evaluate(() => scrollY)).toBe(scroll)
    await controls.getByRole('button', { name: 'Stop song', exact: true }).click()
    await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight))
    const credit = await page.getByText('Inspired by', { exact: false }).boundingBox()
    const dock = await player.boundingBox()
    expect(credit.y + credit.height).toBeLessThan(dock.y)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
}

test('desktop retains one inline set of playback controls when the viewport changes', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/')
  const controls = page.getByRole('group', { name: 'Playback controls', exact: true })
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await controls.getByRole('button', { name: 'Play song', exact: true }).click()
  await page.setViewportSize({ width: 1280, height: 1000 })
  await expect(controls).toHaveCount(1)
  await expect(controls).toHaveCSS('position', 'static')
  await expect(controls.getByRole('button', { name: 'Stop song', exact: true })).toBeVisible()
  const waveform = await page.locator('.waveform-display').boundingBox()
  const inline = await controls.boundingBox()
  expect(inline.y).toBeGreaterThan(waveform.y + waveform.height)
  await controls.getByRole('button', { name: 'Stop song', exact: true }).click()
})
