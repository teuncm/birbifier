import { test, expect } from '@playwright/test'

test('device dark theme is used, theme switching persists, and waveform has no grid or axis', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto('/')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(25, 26, 27)')
  const waveform = page.getByRole('img', { name: 'Waveform preview of the current song' })
  await expect(waveform.locator('pattern, rect')).toHaveCount(0)
  await expect(waveform.locator('path')).toHaveCount(0)
  await expect(page.locator('.waveform-display')).toHaveCSS('height', '80px')
  await expect(waveform.locator('line')).toHaveCount(180)
  await page.screenshot({ path: 'test-results/theme-dark-desktop.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Switch to light theme' }).click()
  await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(225, 230, 217)')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.screenshot({ path: 'test-results/theme-light-desktop.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Switch to dark theme' }).click()
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
})

test('theme toggle works on mobile when storage is unavailable', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.addInitScript(() => {
    Object.defineProperty(window, 'localStorage', { get() { throw new Error('Storage unavailable') } })
  })
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByRole('button', { name: 'Switch to light theme' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.getByRole('button', { name: 'Switch to dark theme' }).click()
  await expect(page.locator('.waveform-display')).toHaveCSS('height', '32px')
  await expect(page.locator('.waveform-display svg line')).toHaveCount(180)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/theme-dark-mobile.png', fullPage: true, animations: 'disabled' })
})

test('theme follows device changes until manually selected', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'light' })
  await page.goto('/')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await expect(page.locator('meta[name="theme-color"]')).toHaveAttribute('content', '#e1e6d9')
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(page.locator('meta[name="theme-color"]')).toHaveAttribute('content', '#191a1b')
  await page.getByRole('button', { name: 'Switch to light theme' }).click()
  await page.emulateMedia({ colorScheme: 'light' })
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
})
